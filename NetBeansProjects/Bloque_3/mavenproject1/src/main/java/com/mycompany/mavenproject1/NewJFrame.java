    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = jTextField1.getText();
        String direccion = jTextField2.getText();
            int telefono = Integer.parseInt(jTextField3.getText());
        
        try {
            InputStream reportStream = getClass().getResourceAsStream("/Ejercicio1.jrxml");
            JasperReport jasperReport = JasperCompileManager.compileReport(reportStream);

            Map<String, Object> parameters = new HashMap<>();
            parameters.put("NombreUsuario", nombre);
            parameters.put("DirecionUsuario", direccion);
            parameters.put("TelefonoUsuario", telefono);

            JREmptyDataSource dataSource = new JREmptyDataSource();

            JasperPrint jasperPrint = JasperFillManager.fillReport(jasperReport, parameters, dataSource);

            String outputPdfPath = "reporte.pdf";
            JasperExportManager.exportReportToPdfFile(jasperPrint, outputPdfPath);
            JasperViewer.viewReport(jasperPrint, false);

            JOptionPane.showMessageDialog(null, "El reporte ha sido generado correctamente como PDF.",
                    "Exito", JOptionPane.INFORMATION_MESSAGE);

        } catch (JRException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error JasperReports: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

